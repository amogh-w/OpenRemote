"""Build assets/ui/icons.html (an SVG <symbol> sprite) from Lucide icons.

Run: python tools/fetch_lucide.py
The generated file is committed, so normal builds and the running app need no network.
Lucide is ISC licensed, see THIRD_PARTY.md.
"""
import re
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "assets" / "ui" / "icons.html"
BASE = "https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/{}.svg"

# symbol id (used as <use href="#i-ID">) -> Lucide icon name
ICONS = {
    # navigation
    "pad": "mouse-pointer-2", "type": "keyboard", "apps": "layout-grid", "media": "circle-play", "more": "ellipsis",
    # pad
    "mouse": "mouse", "click": "mouse-pointer-click", "hand": "hand", "pointer": "pointer", "move": "move",
    "grip": "grip-vertical", "help": "info",
    # media
    "play": "play", "pause": "pause", "prev": "skip-back", "next": "skip-forward",
    "vol-up": "volume-2", "vol-down": "volume-1", "mute": "volume-x", "plus": "plus", "minus": "minus",
    "fullscreen": "fullscreen", "presentation": "presentation",
    # windows and apps
    "window": "app-window", "max": "maximize", "restore": "minimize-2", "x": "x", "search": "search",
    "refresh": "refresh-cw", "check": "check", "loader": "loader-circle",
    # arrows and chevrons
    "left": "chevron-left", "right": "chevron-right", "up": "chevron-up", "down": "chevron-down",
    "arrow-left": "arrow-left", "arrow-right": "arrow-right", "arrow-up": "arrow-up", "arrow-down": "arrow-down",
    # keyboard
    "enter": "corner-down-left", "backspace": "delete", "shift": "arrow-big-up", "caps": "arrow-big-up-dash",
    "command": "command", "globe": "globe",
    # more tiles and pages
    "settings": "settings", "browser": "panel-top", "clipboard": "clipboard-copy", "paste": "clipboard-paste",
    "image": "image", "power": "power", "monitor": "monitor", "home": "house", "external": "external-link", "copy": "copy",
    "sun": "sun", "moon": "moon", "info": "info", "phone": "smartphone", "wifi": "wifi", "wifi-off": "wifi-off",
    # power
    "restart": "rotate-cw", "sleep": "moon", "lock": "lock", "logoff": "log-out", "hibernate": "arrow-down-to-line",
    # computers
    "circle-check": "circle-check",
}


def fetch(name: str) -> str:
    req = urllib.request.Request(BASE.format(name), headers={"User-Agent": "openremote-icon-fetch"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf8")


def inner(svg: str) -> str:
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m:
        raise ValueError("no <svg> element")
    return re.sub(r"\s+", " ", m.group(1)).strip()


def main() -> int:
    symbols, failed = [], []
    for sym, name in ICONS.items():
        try:
            symbols.append(f'<symbol id="i-{sym}" viewBox="0 0 24 24">{inner(fetch(name))}</symbol>')
        except Exception as e:  # keep going so one rename does not hide the rest
            failed.append((sym, name, str(e)))
    if failed:
        for f in failed:
            print("FAILED:", f, file=sys.stderr)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "<!-- Icons: Lucide (https://lucide.dev), ISC license, see THIRD_PARTY.md. Generated by tools/fetch_lucide.py -->\n"
        '<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs>\n'
        + "\n".join(symbols)
        + "\n</defs></svg>\n",
        encoding="utf8",
    )
    print(f"wrote {OUT} ({len(symbols)} icons, {OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
