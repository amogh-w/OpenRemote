"""Generate the iPhone launch images (assets/splash/) and the <link> tags for them in assets/ui/head.html.

Run: python tools/gen_splash.py   (needs Pillow). iOS only shows a launch image that matches the phone's exact size, so there is
one per portrait size, in a dark and a light version (prefers-color-scheme). Android builds its own from the manifest.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_icons  # noqa: E402  (the same tile as the app icon)

ROOT = HERE.parent
OUT = ROOT / "assets" / "splash"
HEAD = ROOT / "assets" / "ui" / "head.html"

# (CSS width, CSS height, pixel ratio): every portrait iPhone size still in use
SIZES = [
    (440, 956, 3), (402, 874, 3), (430, 932, 3), (393, 852, 3), (428, 926, 3), (390, 844, 3),
    (375, 812, 3), (414, 896, 3), (414, 896, 2), (414, 736, 3), (375, 667, 2), (320, 568, 2),
]
# Catppuccin Mocha and Latte: base and text
SCHEMES = {"dark": ((30, 30, 46), (205, 214, 244)), "light": ((239, 241, 245), (76, 79, 105))}
FONTS = ["C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/arialbd.ttf", "DejaVuSans-Bold.ttf"]
START, END = "<!-- splash:start (generated by tools/gen_splash.py) -->", "<!-- splash:end -->"


def font(px):
    for f in FONTS:
        try:
            return ImageFont.truetype(f, px)
        except OSError:
            pass
    return ImageFont.load_default()


def make(w, h, scheme, tile):
    bg, ink = SCHEMES[scheme]
    img = Image.new("RGB", (w, h), bg)
    t = round(w * 0.24)
    tl = tile.resize((t, t), Image.LANCZOS).convert("RGBA")
    mask = Image.new("L", (t, t), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, t - 1, t - 1), round(t * 0.225), fill=255)
    f = font(round(w * 0.052))
    d = ImageDraw.Draw(img)
    name = "OpenRemote"
    tw = d.textlength(name, font=f)
    gap = round(t * 0.22)
    top = round(h * 0.5 - (t + gap + f.size) / 2 - h * 0.02)   # a little above the middle, like the in-page launch screen
    img.paste(tl, ((w - t) // 2, top), mask)
    d.text(((w - tw) / 2, top + t + gap), name, font=f, fill=ink)
    return img


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tile = gen_icons.build()
    links = []
    for cw, ch, dpr in SIZES:
        w, h = cw * dpr, ch * dpr
        for scheme in SCHEMES:
            name = f"{scheme}-{w}x{h}"
            make(w, h, scheme, tile).quantize(256).save(OUT / f"{name}.png", optimize=True)
            media = f"(device-width: {cw}px) and (device-height: {ch}px) and (-webkit-device-pixel-ratio: {dpr}) and (orientation: portrait) and (prefers-color-scheme: {scheme})"
            links.append(f'<link rel="apple-touch-startup-image" href="/splash/{name}.png" media="{media}">')
    block = START + "\n" + "\n".join(links) + "\n" + END
    head = HEAD.read_text(encoding="utf-8")
    crlf = "\r\n" in head
    head = head.replace("\r\n", "\n")
    if START in head:
        a, b = head.index(START), head.index(END) + len(END)
        head = head[:a] + block + head[b:]
    else:
        anchor = '<link rel="apple-touch-icon" href="/icon-180.png">'
        assert head.count(anchor) == 1
        head = head.replace(anchor, anchor + "\n" + block)
    HEAD.write_text(head.replace("\n", "\r\n") if crlf else head, encoding="utf-8", newline="")
    total = sum(p.stat().st_size for p in OUT.glob("*.png"))
    print(f"wrote {len(links)} images ({total // 1024} KB) and their tags in {HEAD.name}")
    names = [f"{s}-{cw * dpr}x{ch * dpr}" for cw, ch, dpr in SIZES for s in SCHEMES]
    print("rust table:", ", ".join(f'"{n}"' for n in names))


if __name__ == "__main__":
    main()
